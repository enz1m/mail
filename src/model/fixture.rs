#[cfg(not(test))]
pub(crate) fn stage_demo_photos(
    messages: &mut [Message],
    store: &crate::attachment_store::AttachmentStore,
) {
    const DINNER: &[u8] = include_bytes!("fixture_assets/dinner.png");
    for attachment in messages
        .iter_mut()
        .flat_map(|message| message.attachments.iter_mut())
        .filter(|attachment| {
            attachment.payload_id.is_none() && attachment.name.starts_with("dinner-")
        })
    {
        if let Ok(staged) = store.stage_inbound(&attachment.name, "image/png", DINNER) {
            *attachment = staged;
        }
    }
}
